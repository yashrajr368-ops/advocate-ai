/**
 * Switch and apply selected language
 */
function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) lang = 'en';

  localStorage.setItem('rathod_legal_lang', lang);
  document.documentElement.lang = lang;

  const t = TRANSLATIONS[lang];

  // Update text content of data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.textContent = t[key];
    }
  });

  // Update HTML content for data-i18n-html elements
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) {
      el.setAttribute('placeholder', t[key]);
    }
  });

  // Update titles
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (t[key] !== undefined) {
      el.setAttribute('title', t[key]);
    }
  });

  // Update Navbar UI label & checkmarks
  const currentLangLabel = document.getElementById('currentLangLabel');
  if (currentLangLabel) {
    currentLangLabel.textContent = lang === 'hi' ? 'हिंदी' : 'English';
  }

  const checkEn = document.getElementById('check-en');
  const checkHi = document.getElementById('check-hi');
  if (checkEn && checkHi) {
    if (lang === 'hi') {
      checkHi.classList.remove('d-none');
      checkEn.classList.add('d-none');
    } else {
      checkEn.classList.remove('d-none');
      checkHi.classList.add('d-none');
    }
  }
}

// Auto-initialize on page load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('rathod_legal_lang') || 'en';
  setLanguage(savedLang);
});